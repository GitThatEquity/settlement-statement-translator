"""Convert the official Appendix A XML files into citable markdown.

Each paragraph gets a stable citation key so a reader can check any claim in
the line dictionary against the government's own words.

Usage:
    python tools/convert_appendix.py

Writes:
    reference/12-cfr-1024-appendix-a-2026.md   key prefix  1024-A
    reference/24-cfr-3500-appendix-a-2007.md   key prefix  3500-A

ASCII output only. No arguments, no network, no interactive prompts.
"""

import os
import re
import hashlib

HERE = os.path.dirname(os.path.abspath(__file__))
REF = os.path.join(os.path.dirname(HERE), "reference")

JOBS = [
    ("12-cfr-1024-appendix-a-2026-official.xml",
     "12-cfr-1024-appendix-a-2026.md",
     "1024-A",
     "Appendix A to Part 1024, Title 12 (current)",
     "Instructions for Completing HUD-1 and HUD-1a Settlement Statements"),
    ("24-cfr-3500-appendix-a-2007-official.xml",
     "24-cfr-3500-appendix-a-2007.md",
     "3500-A",
     "Appendix A to Part 3500, Title 24 (revised as of April 1, 2007)",
     "Instructions for Completing HUD-1 and HUD-1A Settlement Statements"),
]

ENTITIES = [
    ("&#8212;", "--"), ("&#8211;", "-"),
    ("&#8220;", '"'), ("&#8221;", '"'),
    ("&#8216;", "'"), ("&#8217;", "'"),
    ("&#8226;", "*"), ("&#160;", " "),
    ("&amp;", "&"), ("&lt;", "<"), ("&gt;", ">"), ("&quot;", '"'),
]


def clean(fragment):
    """Strip tags, decode the entities that actually appear, force ASCII."""
    text = re.sub(r"<[^>]+>", "", fragment)
    for src, dst in ENTITIES:
        text = text.replace(src, dst)
    text = text.replace("\u2014", "--").replace("\u2013", "-")
    text = text.replace("\u201c", '"').replace("\u201d", '"')
    text = text.replace("\u2018", "'").replace("\u2019", "'")
    text = text.replace("\u00a0", " ")
    text = text.encode("ascii", "replace").decode("ascii")
    return re.sub(r"\s+", " ", text).strip()


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def convert(xml_name, md_name, prefix, citation, title):
    src = os.path.join(REF, xml_name)
    dst = os.path.join(REF, md_name)
    raw = open(src, encoding="utf-8", errors="replace").read()

    blocks = re.findall(r"<(P|HD1|HD2|HED|HEAD)\b[^>]*>(.*?)</\1>", raw, re.S)

    lines = []
    lines.append("# %s" % title)
    lines.append("")
    lines.append("Citation: %s" % citation)
    lines.append("")
    lines.append("Source file: `%s`" % xml_name)
    lines.append("SHA-256: `%s`" % sha256(src))
    lines.append("")
    lines.append("Generated by `tools/convert_appendix.py`. One paragraph per line,")
    lines.append("each with a citation key. Quote these keys, not this summary.")
    lines.append("")
    lines.append("---")
    lines.append("")

    n = 0
    for tag, body in blocks:
        text = clean(body)
        if not text:
            continue
        if tag in ("HD1", "HD2", "HED", "HEAD"):
            lines.append("## %s" % text)
            lines.append("")
            continue
        n += 1
        lines.append("`[%s %d]` %s" % (prefix, n, text))
        lines.append("")

    with open(dst, "w", encoding="ascii", errors="replace", newline="\n") as fh:
        fh.write("\n".join(lines))

    print("wrote %s  (%d paragraphs)" % (md_name, n))
    return n


def main():
    total = 0
    for job in JOBS:
        total += convert(*job)
    print("total paragraphs: %d" % total)


if __name__ == "__main__":
    main()
